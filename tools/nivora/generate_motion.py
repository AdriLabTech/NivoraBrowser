"""Generate Nivora's spring easing curves (docs/ANIMATIONS.md).

CSS has no spring easing, but `linear()` takes any list of samples. This script solves the step
response of a damped spring and writes it as `linear(...)`, so a transition can move the way a
physical object does: it accelerates, overshoots a little and settles, instead of following a fixed
cubic Bezier. The output is the include `src/nivora/theme/nivora-springs.inc.css`.

A preset is a damping ratio (zeta): 1 is critically damped (no overshoot, the smoothest arrival),
lower values overshoot more. Time is normalized: the curve settles within 0.5 % of its target at 1,
so the duration of the transition is the settling time of the spring.

    python3 tools/nivora/generate_motion.py            # write
    python3 tools/nivora/generate_motion.py --check    # exit 1 if the include differs from the generator
"""

import argparse
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUTPUT = ROOT / "src" / "nivora" / "theme" / "nivora-springs.inc.css"

SETTLE = 0.005  # the curve is within this distance of 1 at normalized time 1
SAMPLES = 48

# name -> (damping ratio, what it is for)
PRESETS = {
    "smooth": (1.0, "arrivals with no overshoot: panels, sidebars, large surfaces"),
    "snappy": (0.8, "a slight overshoot: buttons, rows, selection"),
    "bouncy": (0.55, "a visible settle: menus, popovers, the palette"),
    "elastic": (0.38, "a playful wobble: confirmations and badges, used rarely"),
}


def spring(zeta, t):
    """Step response of a unit-mass spring with damping ratio `zeta`, settling at normalized time 1."""
    if zeta >= 1:
        # Critically damped, with omega chosen so that the envelope (1 + omega t) e^{-omega t} reaches SETTLE at t = 1.
        lo, hi = 1.0, 100.0
        for _ in range(60):
            mid = (lo + hi) / 2
            if (1 + mid) * math.exp(-mid) > SETTLE:
                lo = mid
            else:
                hi = mid
        omega = hi
        return 1 - (1 + omega * t) * math.exp(-omega * t)
    omega = -math.log(SETTLE) / zeta  # the envelope e^{-zeta*omega*t} reaches SETTLE at t = 1
    wd = omega * math.sqrt(1 - zeta * zeta)
    decay = math.exp(-zeta * omega * t)
    return 1 - decay * (math.cos(wd * t) + (zeta * omega / wd) * math.sin(wd * t))


def curve(zeta, samples=SAMPLES):
    """The `linear()` easing of a spring: `samples + 1` values from 0 to exactly 1."""
    values = [spring(zeta, i / samples) for i in range(samples + 1)]
    values[0], values[-1] = 0.0, 1.0
    return values


def fmt(value):
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def easing(zeta):
    return "linear(" + ", ".join(fmt(v) for v in curve(zeta)) + ")"


def build():
    lines = [
        "/* This Source Code Form is subject to the terms of the Mozilla Public",
        " * License, v. 2.0. If a copy of the MPL was not distributed with this",
        " * file, You can obtain one at http://mozilla.org/MPL/2.0/. */",
        "",
        "/* Nivora - spring easing curves. GENERATED by tools/nivora/generate_motion.py: do not edit.",
        " *",
        " * Each is the step response of a damped spring, sampled as linear(). The duration of a",
        " * transition that uses one is the time the spring takes to settle. Declarations only: this file is",
        " * included inside the :root block of nivora-tokens.inc.css. */",
        "",
    ]
    for name, (zeta, use) in PRESETS.items():
        peak = max(curve(zeta))
        lines.append(f"/* {name}: damping {zeta}, overshoot {round((peak - 1) * 100, 1)} %; {use} */")
        lines.append(f"--nivora-spring-{name}: {easing(zeta)};")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        ok = OUTPUT.is_file() and OUTPUT.read_text(encoding="utf-8") == text
        print("OK" if ok else f"{OUTPUT.relative_to(ROOT)} differs from the generator; run without --check")
        return 0 if ok else 1
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

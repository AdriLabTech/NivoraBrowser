# Build Nivora from a fresh checkout and leave the files `makepkg` needs in an output directory.
# It repeats the procedure of docs/BUILDING.md section 2, which was run by hand on Ubuntu 24.04
# (4 cores, 15 GB RAM): that is the configuration the CI workflow and the container route of the
# README use. Other systems are untested.
#
#   1. checks the tools and the free disk space (30 GB);
#   2. installs the Node dependencies (`npm ci`);
#   3. fetches the Firefox source named in surfer.json into engine/ (a shallow clone of Mozilla's
#      GitHub mirror at the release tag);
#   4. imports Zen's patches and Nivora's files (`npm run import`);
#   5. writes the local `mozconfig` (see --print-mozconfig);
#   6. builds (`surfer build`), packages (`mach package`) and assembles the Arch package inputs
#      (tools/nivora/make_arch_package.sh), then checks the PKGBUILD's dependencies against the build.
#
# Usage: build_linux.sh [options]
#   --out DIR               where to leave the package files (default: out/ in the checkout)
#   --jobs N                parallel compile jobs (default: number of CPUs)
#   --apt                   install the system packages with apt-get first (Debian and Ubuntu; uses sudo
#                           unless run as root)
#   --clang-suffix S        suffix of the clang binaries: "-19" for Ubuntu 24.04's clang-19, "" for a
#                           distribution whose `clang` is already 19 or newer (default: -19)
#   --libclang-path DIR     directory of libclang.so (default: /usr/lib/llvm-19/lib)
#   --no-disk-check         do not stop when there is less than 30 GB free
#   --print-mozconfig       print the mozconfig that would be written, and exit
#   --dry-run               print the steps and exit
#
# Nothing here installs anything outside the checkout except with --apt, and nothing is published.
set -euo pipefail

root=$(cd "$(dirname "$0")/../.." && pwd)
out="$root/out"
jobs=$(nproc 2>/dev/null || echo 4)
use_apt=0
clang_suffix="-19"
libclang_path="/usr/lib/llvm-19/lib"
disk_check=1
mode=build

while [ $# -gt 0 ]; do
  case "$1" in
    --out) out=$2; shift 2 ;;
    --jobs) jobs=$2; shift 2 ;;
    --apt) use_apt=1; shift ;;
    --clang-suffix) clang_suffix=$2; shift 2 ;;
    --libclang-path) libclang_path=$2; shift 2 ;;
    --no-disk-check) disk_check=0; shift ;;
    --print-mozconfig) mode=mozconfig; shift ;;
    --dry-run) mode=dry; shift ;;
    -h|--help) sed -n '2,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "error: unknown option $1 (see --help)" >&2; exit 2 ;;
  esac
done

marker="# Generated by tools/nivora/build_linux.sh: delete this line to keep your own edits."

mozconfig() {
  cat <<EOF
$marker
# Minimal opt build: not the release configuration (that is configs/common/mozconfig with ZEN_RELEASE=1,
# which enables LTO, PGO and Widevine and needs mach bootstrap toolchains). See docs/BUILDING.md.
ac_add_options --disable-crashreporter
ac_add_options --disable-debug-symbols
ac_add_options --disable-geckodriver
ac_add_options --disable-rust-tests
ac_add_options --disable-updater
ac_add_options --without-wasm-sandboxed-libraries
ac_add_options --enable-linker=lld
mk_add_options MOZ_MAKE_FLAGS="-j$jobs"

# Firefox 158 needs clang 19 or newer.
export CC=clang$clang_suffix
export CXX=clang++$clang_suffix
export HOST_CC=clang$clang_suffix
export HOST_CXX=clang++$clang_suffix
ac_add_options --with-libclang-path=$libclang_path
ac_add_options --with-clang-path=/usr/bin/clang$clang_suffix

# Zen's linux mozconfig sets MOZ_STDCXX_COMPAT=1, an old-glibc compatibility shim whose
# stdc++compat.cpp does not compile against GCC 13 headers; a local build does not need it.
unset MOZ_STDCXX_COMPAT
EOF
}

if [ "$mode" = mozconfig ]; then
  mozconfig
  exit 0
fi

step() { printf '\n==> %s\n' "$1"; }

firefox_tag() {
  python3 - "$root/surfer.json" <<'PY'
import json, sys
version = json.load(open(sys.argv[1]))["version"]["version"]
print("FIREFOX_" + version.replace(".", "_") + "_RELEASE")
PY
}

if [ "$mode" = dry ]; then
  cat <<EOF
would run, in $root:
  1. check tools and disk
  2. apt-get install the system packages (only with --apt; now: $([ "$use_apt" = 1 ] && echo yes || echo no))
  3. npm ci
  4. git clone --depth 1 --branch $(firefox_tag) https://github.com/mozilla-firefox/firefox engine   (if engine/ is absent)
  5. npx surfer set brand release; npx surfer set buildMode dev; npm run import
  6. write mozconfig (clang$clang_suffix, libclang $libclang_path, -j$jobs)
  7. npx surfer build --jobs $jobs; engine/mach package
  8. tools/nivora/make_arch_package.sh -> $out; tools/nivora/check_arch_deps.py
EOF
  exit 0
fi

cd "$root"
# Identity for the commits surfer makes inside engine/; set for this run only, never written to a git config.
export GIT_AUTHOR_NAME=${GIT_AUTHOR_NAME:-Nivora build} GIT_AUTHOR_EMAIL=${GIT_AUTHOR_EMAIL:-build@localhost}
export GIT_COMMITTER_NAME=${GIT_COMMITTER_NAME:-Nivora build} GIT_COMMITTER_EMAIL=${GIT_COMMITTER_EMAIL:-build@localhost}

if [ "$use_apt" = 1 ]; then
  step "System packages (apt)"
  sudo=""; [ "$(id -u)" = 0 ] || sudo=sudo
  $sudo apt-get update
  # The list of docs/BUILDING.md section 2.1, plus the compilers and tools that were already on the
  # reference image (build-essential, pkg-config, nasm, git, curl, xz-utils).
  $sudo apt-get install -y --no-install-recommends \
    build-essential pkg-config nasm yasm m4 autoconf2.13 git curl ca-certificates xz-utils unzip zip \
    python3 python3-venv python3-pip \
    libgtk-3-dev libdbus-glib-1-dev libdbus-1-dev libpulse-dev libasound2-dev libxt-dev \
    libstartup-notification0-dev libx11-xcb-dev libdrm-dev libcurl4-openssl-dev \
    libxcomposite-dev libxdamage-dev libxrandr-dev libxcursor-dev libxi-dev libgbm-dev \
    libxkbcommon-dev \
    "clang$clang_suffix" "libclang$clang_suffix-dev" "llvm$clang_suffix-dev" "lld$clang_suffix"
fi

step "Checking tools and disk"
missing=0
for tool in node npm python3 git cargo rustc clang"$clang_suffix" clang++"$clang_suffix" nasm; do
  command -v "$tool" >/dev/null || { echo "missing: $tool" >&2; missing=1; }
done
command -v cbindgen >/dev/null || { echo "cbindgen is not installed: cargo install cbindgen --version 0.29.4 --locked" >&2; missing=1; }
command -v ld.lld"$clang_suffix" >/dev/null || command -v ld.lld >/dev/null || { echo "missing: lld" >&2; missing=1; }
[ "$missing" = 0 ] || { echo "error: install the missing tools (docs/BUILDING.md section 1, or use --apt)" >&2; exit 2; }
clang_major=$("clang$clang_suffix" --version | sed -n 's/.*version \([0-9]*\)\..*/\1/p' | head -1)
[ "${clang_major:-0}" -ge 19 ] || { echo "error: clang $clang_major found, Firefox 158 needs 19 or newer" >&2; exit 2; }
if [ "$disk_check" = 1 ]; then
  free_gb=$(df --output=avail -BG "$root" | tail -1 | tr -dc '0-9')
  [ "${free_gb:-0}" -ge 30 ] || { echo "error: ${free_gb:-?} GB free in $root; 30 GB are needed (--no-disk-check to ignore)" >&2; exit 2; }
fi
echo "node $(node --version), rustc $(rustc --version | cut -d' ' -f2), clang $clang_major, $(nproc) CPUs, jobs $jobs"

step "npm ci"
[ -d node_modules/@zen-browser ] || npm ci

if [ ! -d engine/.git ]; then
  tag=$(firefox_tag)
  step "Firefox source: $tag (shallow clone of Mozilla's GitHub mirror)"
  [ ! -e engine ] || { echo "error: engine/ exists but is not a git checkout; move it away" >&2; exit 2; }
  git clone --depth 1 --branch "$tag" https://github.com/mozilla-firefox/firefox engine
else
  echo "engine/ already exists: reused as it is (a patched tree needs 'git -C engine checkout -f -- . && git -C engine clean -fd' before a new import, see docs/BUILDING.md 2.3)"
fi

step "Import Zen's patches and Nivora's files"
npx surfer set brand release
npx surfer set buildMode dev
npm run import

step "mozconfig"
if [ -e mozconfig ] && ! grep -qF "$marker" mozconfig; then
  echo "error: ./mozconfig exists and was not written by this script; move it away or edit the toolchain lines yourself" >&2
  exit 2
fi
mozconfig > mozconfig

step "Build (about 80 minutes on 4 cores)"
npx surfer build --jobs "$jobs"

step "Package"
(cd engine && ./mach package)
dist=$(ls -d engine/obj-*/dist/nivora | head -1)
tools/nivora/make_arch_package.sh "$dist" "$out"
python3 tools/nivora/check_arch_deps.py --dist "$dist"

echo
echo "done: $out"
ls -la "$out"

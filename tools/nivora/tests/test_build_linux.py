"""tools/nivora/build_linux.sh: the parts that do not build anything."""

import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCRIPT = ROOT / "tools" / "nivora" / "build_linux.sh"


def run(*args):
    return subprocess.run(["bash", str(SCRIPT), *args], capture_output=True, text=True, timeout=60)


def config(*args):
    result = run("--print-mozconfig", *args)
    assert result.returncode == 0, result.stderr
    return result.stdout


class ScriptTest(unittest.TestCase):
    def test_the_script_is_valid_bash_and_executable(self):
        self.assertEqual(subprocess.run(["bash", "-n", str(SCRIPT)]).returncode, 0)
        self.assertTrue(SCRIPT.stat().st_mode & 0o111, "not executable")

    def test_the_default_mozconfig_is_the_verified_one(self):
        text = config()
        for line in ("ac_add_options --disable-updater", "ac_add_options --enable-linker=lld",
                     "ac_add_options --without-wasm-sandboxed-libraries", "export CC=clang-19",
                     "export CXX=clang++-19", "ac_add_options --with-libclang-path=/usr/lib/llvm-19/lib",
                     "unset MOZ_STDCXX_COMPAT"):
            self.assertIn(line, text)

    def test_jobs_and_clang_names_are_parameters(self):
        text = config("--jobs", "7", "--clang-suffix", "", "--libclang-path", "/usr/lib")
        self.assertIn('MOZ_MAKE_FLAGS="-j7"', text)
        self.assertIn("export CC=clang\n", text)
        self.assertIn("--with-clang-path=/usr/bin/clang\n", text)
        self.assertIn("--with-libclang-path=/usr/lib\n", text)

    def test_the_mozconfig_names_no_machine_specific_path(self):
        self.assertNotIn("/home/", config())
        self.assertNotIn("/root", config())

    def test_the_mozconfig_carries_the_marker_that_lets_the_script_overwrite_it(self):
        self.assertTrue(config().startswith("# Generated by tools/nivora/build_linux.sh"))

    def test_the_dry_run_names_the_firefox_tag_from_surfer_json(self):
        out = run("--dry-run").stdout
        self.assertIn("--branch FIREFOX_158_0_1_RELEASE", out)
        self.assertIn("npm run import", out)

    def test_an_unknown_option_is_refused(self):
        result = run("--bogus")
        self.assertEqual(result.returncode, 2)
        self.assertIn("unknown option", result.stderr)

    def test_nothing_in_the_script_publishes_or_writes_outside_the_checkout_without_apt(self):
        text = SCRIPT.read_text(encoding="utf-8")
        for forbidden in ("git push", "gh release", "git config --global", "pacman -S", "rm -rf /"):
            self.assertNotIn(forbidden, text)


WORKFLOW = ROOT / ".github" / "workflows" / "nivora-build-linux.yml"


class WorkflowTest(unittest.TestCase):
    """The build workflow is started by hand, only reads the repository and publishes nothing."""

    def setUp(self):
        self.text = WORKFLOW.read_text(encoding="utf-8")

    def test_it_starts_only_by_hand(self):
        self.assertIn("workflow_dispatch:", self.text)
        for trigger in ("push:", "pull_request:", "schedule:"):
            self.assertNotIn(f"\n  {trigger}", self.text)

    def test_it_can_only_read_the_repository(self):
        self.assertIn("permissions:\n  contents: read", self.text)
        for forbidden in ("contents: write", "gh release", "softprops", "git push"):
            self.assertNotIn(forbidden, self.text)

    def test_it_runs_the_same_script_the_readme_tells_a_person_to_run(self):
        self.assertIn("tools/nivora/build_linux.sh --apt", self.text)

    def test_the_artifact_is_short_lived(self):
        self.assertIn("retention-days: 14", self.text)


if __name__ == "__main__":
    unittest.main()

"""Generate Zen's interface icons from Phosphor Icons (MIT).

Zen ships 154 icons made with Nucleo, whose notice reads: "Redistribution is not permitted. Use in
source and binary forms ... is permitted only if you possess a Nucleo license." Nivora has no such
license, so every file in src/browser/themes/shared/zen-icons/nucleo/ is regenerated from the
Phosphor Icons set, which is MIT licensed. File names and the way the files are packaged do not
change, so no other file needs to know.

The mapping from each Zen icon name to a Phosphor glyph is tools/nivora/icons/map.json.

Usage:
  generate_icons.py --phosphor DIR [--out DIR]   write the icons
  generate_icons.py --check [--out DIR]           verify the icons already in the tree

`--phosphor` is the `assets` directory of the npm package `@phosphor-icons/core` (version 2.1.1 was
used): `npm pack @phosphor-icons/core && tar xzf phosphor-icons-core-*.tgz` gives `package/assets`.
"""

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DEFAULT_OUT = ROOT / "src" / "browser" / "themes" / "shared" / "zen-icons" / "nucleo"
MAP_FILE = HERE / "icons" / "map.json"

MARKER = "Phosphor Icons"

HEADER = (
    "#filter dumbComments emptyLines substitution\n"
    f"# {MARKER}, MIT License. See phosphor-LICENSE.txt in this directory.\n"
    "# Generated by tools/nivora/generate_icons.py from tools/nivora/icons/map.json; do not edit.\n"
)

SVG_OPEN = (
    '<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" fill="context-fill" '
    'fill-opacity="context-fill-opacity" viewBox="0 0 256 256">'
)

# A diagonal slash from the top left to the bottom right (a thin bar), and a wider bar of the same
# line used to cut a gap in the glyph underneath so the slash stays legible.
SLASH = "M34.34 45.66 45.66 34.34 221.66 210.34 210.34 221.66Z"
SLASH_GAP = "M25.86 54.14 54.14 25.86 230.14 201.86 201.86 230.14Z"

INNER = re.compile(r"<svg[^>]*>(.*)</svg>", re.S)


class IconError(Exception):
    pass


def glyph(phosphor, name, weight):
    """The inner markup of one Phosphor glyph."""
    # The outline weight is Phosphor's "bold": its stroke (about 1.7 px at 18 px) is the closest to
    # the 1.5 px strokes of the icons being replaced; "regular" (about 1.1 px) looks faint on a dark UI.
    folder = "fill" if weight == "fill" else "bold"
    suffix = "-fill" if weight == "fill" else "-bold"
    path = Path(phosphor) / folder / f"{name}{suffix}.svg"
    if not path.is_file():
        raise IconError(f"Phosphor glyph not found: {path}")
    match = INNER.search(path.read_text(encoding="utf-8"))
    if not match:
        raise IconError(f"cannot read {path}")
    return match.group(1).strip()


def build(phosphor, spec):
    """One complete icon file, as text."""
    markup = glyph(phosphor, spec["icon"], spec.get("weight", "regular"))
    if spec.get("flip"):
        markup = f'<g transform="matrix(-1 0 0 1 256 0)">{markup}</g>'
    if spec.get("slash"):
        markup = (
            f'<defs><mask id="gap"><rect width="256" height="256" fill="#fff"/>'
            f'<path d="{SLASH_GAP}" fill="#000"/></mask></defs>'
            f'<g mask="url(#gap)">{markup}</g><path d="{SLASH}"/>'
        )
    return f"{HEADER}{SVG_OPEN}{markup}</svg>\n"


def generate(phosphor, out):
    """Write every mapped icon; return the number written."""
    mapping = json.loads(MAP_FILE.read_text(encoding="utf-8"))["icons"]
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name, spec in mapping.items():
        (out / f"{name}.svg").write_text(build(phosphor, spec), encoding="utf-8")
    return len(mapping)


def check(out):
    """Problems with the icons in `out`; an empty list means they are all Nivora's."""
    out = Path(out)
    problems = []
    mapping = json.loads(MAP_FILE.read_text(encoding="utf-8"))["icons"]
    on_disk = {p.stem for p in out.glob("*.svg")}
    for name in sorted(on_disk - set(mapping)):
        problems.append(f"{name}.svg is not in the map (a new Zen icon? map it, then regenerate)")
    for name in sorted(set(mapping) - on_disk):
        problems.append(f"{name}.svg is mapped but missing")
    for path in sorted(out.glob("*.svg")):
        text = path.read_text(encoding="utf-8")
        if MARKER not in text:
            problems.append(f"{path.name} was not generated from Phosphor Icons")
        if "nucleo" in text.lower():
            problems.append(f"{path.name} mentions Nucleo")
    if (out / "nucleo-copyright-notice.html").exists():
        problems.append("nucleo-copyright-notice.html is still present")
    if not (out / "phosphor-LICENSE.txt").is_file():
        problems.append("phosphor-LICENSE.txt is missing")
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--phosphor", type=Path, help="the `assets` directory of @phosphor-icons/core")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    args = parser.parse_args(argv)
    if args.check:
        problems = check(args.out)
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        print("icons ok" if not problems else f"{len(problems)} problem(s)")
        return 1 if problems else 0
    if not args.phosphor:
        parser.error("--phosphor is required unless --check is given")
    try:
        count = generate(args.phosphor, args.out)
    except IconError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    print(f"wrote {count} icons to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
